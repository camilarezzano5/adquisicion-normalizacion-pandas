# PASO 2: ADQUISICION DE DATOS

import pandas as pd

# Cargar archivo CSV
transacciones = pd.read_csv("transacciones.csv")

# Cargar archivo Excel
productos = pd.read_excel("productos.xlsx", engine="openpyxl")

# Mostrar las primeras filas
print("DATOS DE TRANSACCIONES:")
display(transacciones.head())

print("CATALOGO DE PRODUCTOS:")
display(productos.head())

# Verificar dimensiones
print("Dimensiones de transacciones:", transacciones.shape)
print("Dimensiones de productos:", productos.shape)

# PASO 3: LIMPIEZA Y NORMALIZACION

# 1. Verificar tipos de datos
print("Tipos de datos originales:")
print(transacciones.dtypes)
print(productos.dtypes)

# 2. Convertir identificadores a tipo entero
transacciones["id_producto"] = pd.to_numeric(
    transacciones["id_producto"], errors="coerce"
)

productos["id_producto"] = pd.to_numeric(
    productos["id_producto"], errors="coerce"
)

# 3. Convertir cantidad y precio a valores numericos
transacciones["cantidad"] = pd.to_numeric(
    transacciones["cantidad"], errors="coerce"
)

productos["precio_unitario"] = pd.to_numeric(
    productos["precio_unitario"], errors="coerce"
)

# 4. Convertir fecha a formato datetime
transacciones["fecha"] = pd.to_datetime(
    transacciones["fecha"],
    format="%d/%m/%Y",
    errors="coerce"
)

# 5. Eliminar valores nulos en campos criticos
transacciones = transacciones.dropna(
    subset=["id_producto", "cantidad", "fecha"]
)

productos = productos.dropna(
    subset=["id_producto", "nombre_producto", "precio_unitario"]
)

# 6. Convertir identificadores a enteros
transacciones["id_producto"] = transacciones["id_producto"].astype(int)
productos["id_producto"] = productos["id_producto"].astype(int)

# 7. Eliminar productos duplicados
productos = productos.drop_duplicates(
    subset=["id_producto"]
)

# 8. Mostrar resultados
print("\nTipos de datos despues de la limpieza:")
print(transacciones.dtypes)
print(productos.dtypes)

print("\nValores nulos en transacciones:")
print(transacciones.isnull().sum())

print("\nValores nulos en productos:")
print(productos.isnull().sum())

print("\nTransacciones limpias:")
display(transacciones.head())

print("\nProductos limpios:")
display(productos)

# PASO 4: INTEGRACION DE DATOS

# Unir transacciones con el catalogo de productos
ventas = pd.merge(
    transacciones,
    productos,
    on="id_producto",
    how="inner"
)

# Mostrar el resultado
print("DATASET INTEGRADO:")
display(ventas)

# Verificar dimensiones
print("Cantidad de filas y columnas:", ventas.shape)

# Verificar si quedaron valores nulos
print("\nValores nulos:")
print(ventas.isnull().sum())

# PASO 5: CREACION DE LA COLUMNA CALCULADA

# Calcular el total de cada venta
ventas["total_venta"] = (
    ventas["cantidad"] * ventas["precio_unitario"]
)

# Mostrar el dataset actualizado
print("DATASET CON TOTAL DE VENTAS:")
display(ventas)

# Calcular el total general vendido
print("Total general de ventas: $", ventas["total_venta"].sum())

# Verificar valores nulos
print("\nValores nulos:")
print(ventas.isnull().sum())

# Verificar tipos de datos
print("\nTipos de datos:")
print(ventas.dtypes)

